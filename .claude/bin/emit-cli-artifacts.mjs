#!/usr/bin/env node
/**
 * emit-cli-artifacts.mjs — generate the Codex and Gemini CLI lanes from `.claude/`.
 *
 * Astrolabe's substrate is authored ONCE in Claude Code dialect under `.claude/`.
 * This emitter derives the other two CLI lanes from it, so there is exactly one
 * editing site and the lanes cannot silently drift apart.
 *
 *   SOURCE (authored)          →  EMITTED (generated — do not hand-edit)
 *   CLAUDE.md + rules/*.md     →  AGENTS.md (Codex), GEMINI.md (Gemini)
 *   settings.json hooks        →  .codex/hooks.json, .gemini/settings.json
 *   commands/*.md              →  .codex/prompts/*.md, .gemini/commands/*.toml
 *   skills/<n>/SKILL.md        →  .codex/skills/<n>/, .gemini/skills/<n>/
 *   agents/**.md               →  .gemini/agents/*.md (tool names translated)
 *   —                          →  .codex/config.toml, bin/astro
 *
 * Usage:
 *   node .claude/bin/emit-cli-artifacts.mjs            # write the lanes
 *   node .claude/bin/emit-cli-artifacts.mjs --check    # drift check, exit 1 if stale
 *   node .claude/bin/emit-cli-artifacts.mjs --root <d> # operate on another instance
 *
 * The emitted trees are COMMITTED (like loom's) so a fresh clone is immediately
 * multi-CLI without a build step, and so drift is visible in review.
 */

import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const rootFlag = args.indexOf("--root");
const ROOT = rootFlag >= 0 ? path.resolve(args[rootFlag + 1]) : process.cwd();
const D = path.join(ROOT, ".claude");

const BANNER = "GENERATED by .claude/bin/emit-cli-artifacts.mjs — DO NOT EDIT. Edit the .claude/ source and re-run.";

let written = 0;
let stale = [];

function put(rel, content) {
  const abs = path.join(ROOT, rel);
  const prev = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (prev === content) return;
  if (CHECK) {
    stale.push(rel);
    return;
  }
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
  written++;
}

const read = (f) => fs.readFileSync(f, "utf8");
const listMd = (d) => (fs.existsSync(d) ? fs.readdirSync(d).filter((f) => f.endsWith(".md")).sort() : []);

function splitFrontmatter(src) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { fm: {}, body: src };
  const fm = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) fm[kv[1]] = kv[2].replace(/^["']|["']$/g, "");
  }
  return { fm, body: m[2] };
}

/**
 * Rewrite CC-specific markdown syntax for a target lane.
 *
 *   !`cmd`            CC auto-executes this before the prompt renders. Neither
 *                     Codex nor Gemini has that primitive, so it becomes an
 *                     explicit instruction + fenced command the agent must run.
 *   $CLAUDE_PROJECT_DIR   Codex exports NO project-dir variable (verified — a
 *                     `$CODEX_PROJECT_DIR` expands empty and the command dies with
 *                     MODULE_NOT_FOUND), so Codex gets repo-relative paths.
 *   $ARGUMENTS        Gemini's custom-command placeholder is {{args}}.
 */
function translateBody(body, lane) {
  let out = body;

  out = out.replace(/^!`(.+?)`\s*$/gm, (_m, cmd) =>
    ["**Run this first** (deterministic — do not answer from memory):", "", "```bash", cmd.trim(), "```"].join("\n"),
  );

  if (lane === "codex") {
    out = out.replace(/\$CLAUDE_PROJECT_DIR\//g, "./").replace(/"\$CLAUDE_PROJECT_DIR"\//g, "./");
    out = out.replace(/\$CLAUDE_PROJECT_DIR/g, ".");
  } else if (lane === "gemini") {
    out = out.replace(/\$CLAUDE_PROJECT_DIR/g, "$GEMINI_PROJECT_DIR");
    out = out.replace(/\$ARGUMENTS/g, "{{args}}");
  }
  return out;
}

// Gemini agent frontmatter uses lane-native tool names.
const GEMINI_TOOLS = {
  Bash: "run_shell_command",
  Read: "read_file",
  Write: "write_file",
  Edit: "replace",
  Grep: "grep_search",
  Glob: "glob",
  WebFetch: "web_fetch",
  WebSearch: "google_web_search",
};

// ── 1. Root context docs: AGENTS.md (Codex) + GEMINI.md (Gemini) ──────────────
// Both CLIs load a single root doc by directory-hierarchy walk; neither honors
// CC's per-rule `paths:` frontmatter. So the rules are INLINED here — that is the
// only delivery channel these lanes have for always-on policy.
function emitRootDocs() {
  const claudeMd = read(path.join(ROOT, "CLAUDE.md"));
  const rules = listMd(path.join(D, "rules"));

  for (const [lane, file] of [["codex", "AGENTS.md"], ["gemini", "GEMINI.md"]]) {
    const parts = [
      `<!-- ${BANNER} -->`,
      "",
      `# Astrolabe — ${lane === "codex" ? "Codex" : "Gemini"} CLI context`,
      "",
      "> This repository is authored in Claude Code dialect under `.claude/`. This file is the",
      `> generated ${lane} lane: the same project instructions plus every global rule inlined,`,
      "> because this CLI has no per-rule conditional loader. **The governance rules below are",
      "> binding on this lane exactly as they are in Claude Code.**",
      "",
      "---",
      "",
      translateBody(claudeMd, lane),
      "",
      "---",
      "",
      "# Global Rules (inlined — all binding)",
      "",
    ];
    for (const r of rules) {
      const { body } = splitFrontmatter(read(path.join(D, "rules", r)));
      parts.push(`## rules/${r}`, "", translateBody(body, lane).trim(), "");
    }

    // Agent roster: Codex/Gemini spawn subagents by natural language, so the
    // roster has to be visible in the context doc rather than a tools manifest.
    const agentDir = path.join(D, "agents");
    const roster = [];
    const walk = (dir) => {
      if (!fs.existsSync(dir)) return;
      for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) walk(p);
        else if (e.name.endsWith(".md")) {
          const { fm } = splitFrontmatter(read(p));
          if (fm.name) roster.push(`- **${fm.name}** — ${fm.description || ""}`);
        }
      }
    };
    walk(agentDir);
    if (roster.length) {
      parts.push("---", "", "# Specialist Agents", "");
      if (lane === "gemini") {
        parts.push("Defined natively in `.gemini/agents/`. Delegate to them by name.", "");
      } else {
        parts.push(
          "Codex has no agent-manifest format; spawn these as subagents by name and role",
          "(e.g. \"Act as **bazi-analyst**: ...\"), honoring the constraints in their description.",
          "",
        );
      }
      parts.push(...roster.sort(), "");
    }
    put(file, parts.join("\n"));
  }
}

// ── 2. Hooks: translate .claude/settings.json into each lane's dialect ────────
// Event names, matcher tool names and the project-dir variable all differ; the
// hook SCRIPTS are shared, run through lane-adapter.js which normalizes the
// payload and the verdict. See .claude/hooks/lib/lane.js for the maps.
const EVENT = {
  codex: { PreToolUse: "PreToolUse", PostToolUse: "PostToolUse", UserPromptSubmit: "UserPromptSubmit", SessionStart: "SessionStart", Stop: "Stop" },
  gemini: { PreToolUse: "BeforeTool", PostToolUse: "AfterTool", UserPromptSubmit: "BeforeModel", SessionStart: "SessionStart", Stop: "SessionEnd" },
};
const MATCHER = {
  // CC matcher regex → lane-native tool-name regex
  codex: { "Edit|Write|NotebookEdit": "apply_patch|write", Bash: "shell" },
  gemini: { "Edit|Write|NotebookEdit": "write_file|replace", Bash: "run_shell_command" },
};

function hookCmd(scriptRel, lane) {
  const adapter = ".claude/hooks/lib/lane-adapter.js";
  // Codex: repo-relative (no project-dir env var exists). Gemini: $GEMINI_PROJECT_DIR.
  const pfx = lane === "gemini" ? "$GEMINI_PROJECT_DIR/" : "./";
  return `node ${pfx}${adapter} --lane=${lane} ${pfx}${scriptRel}`;
}

function emitHooks() {
  const settings = JSON.parse(read(path.join(D, "settings.json")));
  const src = settings.hooks || {};

  for (const lane of ["codex", "gemini"]) {
    const out = {};
    for (const [ccEvent, groups] of Object.entries(src)) {
      const ev = EVENT[lane][ccEvent];
      if (!ev) continue;
      out[ev] = groups.map((g) => {
        const o = {};
        if (g.matcher) o.matcher = MATCHER[lane][g.matcher] || g.matcher;
        o.hooks = g.hooks.map((h) => {
          const m = h.command.match(/hooks\/([\w.-]+\.js)/);
          const rel = m ? `.claude/hooks/${m[1]}` : h.command;
          return { type: "command", command: hookCmd(rel, lane) };
        });
        return o;
      });
    }

    if (lane === "codex") {
      // MEASURED 2026-08-08 against Codex v0.147.0: this file is NOT honored.
      // An instrumented probe hook registered here (and, separately, in a
      // user-global CODEX_HOME/hooks.json) was never invoked, while the shell
      // command itself ran — so Codex has no live hook surface on this version.
      // It is emitted for forward-compatibility ONLY. Canon protection on the
      // Codex lane comes from AGENTS.md (soft, model-honored — verified live)
      // plus .githooks/pre-commit (hard, lane-agnostic). Do not treat the
      // presence of this file as enforcement. Re-run the probe after a Codex
      // upgrade; if hooks start firing, this becomes live with no edits needed.
      put(
        ".codex/hooks.json",
        JSON.stringify(
          {
            _note:
              "NOT HONORED by Codex v0.147.0 (measured 2026-08-08 — probe hook never invoked, " +
              "repo-local AND user-global). Emitted for forward-compatibility. Real enforcement on " +
              "this lane: AGENTS.md (soft) + .githooks/pre-commit (hard). See rules/multi-cli.md.",
            hooks: out,
          },
          null,
          2,
        ) + "\n",
      );
    } else {
      const gs = {
        _generated: BANNER,
        _note:
          "Hook wiring is UNVERIFIED live: the available Gemini account returns " +
          "IneligibleTierError on gemini 0.41.2, so end-to-end enforcement could not be " +
          "exercised (2026-08-08). The lane-adapter translation IS covered by subprocess " +
          "tests using Gemini-native payloads. Re-verify with a working account before " +
          "relying on this lane for canon protection. See rules/multi-cli.md.",
        mcpServers: {},
        hooks: out,
      };
      const mcpPath = path.join(ROOT, ".mcp.json");
      if (fs.existsSync(mcpPath)) {
        const mcp = JSON.parse(read(mcpPath));
        gs.mcpServers = mcp.mcpServers || mcp;
      }
      put(".gemini/settings.json", JSON.stringify(gs, null, 2) + "\n");
    }
  }
}

// ── 3. Codex config.toml ─────────────────────────────────────────────────────
function emitCodexConfig() {
  const agentsBytes = fs.existsSync(path.join(ROOT, "AGENTS.md"))
    ? fs.statSync(path.join(ROOT, "AGENTS.md")).size
    : 0;
  const mcpPath = path.join(ROOT, ".mcp.json");
  let mcpBlocks = "";
  if (fs.existsSync(mcpPath)) {
    const mcp = JSON.parse(read(mcpPath));
    for (const [name, cfg] of Object.entries(mcp.mcpServers || mcp)) {
      mcpBlocks += `\n[mcp_servers.${name}]\ncommand = ${JSON.stringify(cfg.command)}\n`;
      if (cfg.args) mcpBlocks += `args = ${JSON.stringify(cfg.args)}\n`;
    }
  }
  put(
    ".codex/config.toml",
    `# ${BANNER}
#
# AGENTS.md carries the project instructions PLUS all inlined global rules, which
# exceeds Codex's 32,768-byte default project-doc cap (currently ${agentsBytes} B).
# Without this raise, Codex silently TRUNCATES the governance rules — including the
# canon-protection and convergence rules — so this value is load-bearing, not cosmetic.
project_doc_max_bytes = 65536
${mcpBlocks}`,
  );
}

// ── 4. Commands → Codex prompts + Gemini TOML commands ───────────────────────
function tomlEscape(s) {
  // Multi-line basic strings can't contain an unescaped triple-quote run.
  return s.replace(/'''/g, "\\'\\'\\'");
}

function emitCommands() {
  const dir = path.join(D, "commands");
  for (const f of listMd(dir)) {
    const name = f.replace(/\.md$/, "");
    const { fm, body } = splitFrontmatter(read(path.join(dir, f)));
    const desc = fm.description || name;

    put(
      `.codex/prompts/${name}.md`,
      `---\nname: ${name}\ndescription: "${desc.replace(/"/g, '\\"')}"\n---\n\n<!-- ${BANNER} -->\n\n${translateBody(body, "codex").trim()}\n`,
    );

    put(
      `.gemini/commands/${name}.toml`,
      `# ${BANNER}\nname = "${name}"\ndescription = ${JSON.stringify(desc)}\nprompt = '''\n${tomlEscape(translateBody(body, "gemini").trim())}\n'''\n`,
    );
  }
}

// ── 5. Skills → native skill dirs on both lanes ──────────────────────────────
function emitSkills() {
  const dir = path.join(D, "skills");
  if (!fs.existsSync(dir)) return;
  for (const s of fs.readdirSync(dir).sort()) {
    const src = path.join(dir, s, "SKILL.md");
    if (!fs.existsSync(src)) continue;
    const { fm, body } = splitFrontmatter(read(src));
    for (const lane of ["codex", "gemini"]) {
      const head = `---\nname: ${fm.name || s}\ndescription: ${JSON.stringify(fm.description || "")}\n---\n\n<!-- ${BANNER} -->\n\n`;
      put(`.${lane}/skills/${s}/SKILL.md`, head + translateBody(body, lane).trim() + "\n");
    }
  }
}

// ── 6. Agents → Gemini native agent files ────────────────────────────────────
function emitAgents() {
  const dir = path.join(D, "agents");
  if (!fs.existsSync(dir)) return;
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith(".md")) {
        const { fm, body } = splitFrontmatter(read(p));
        if (!fm.name) continue;
        const tools = (fm.tools || "")
          .split(",")
          .map((t) => t.trim())
          .filter(Boolean)
          .map((t) => GEMINI_TOOLS[t] || t);
        const head = [
          "---",
          `name: ${fm.name}`,
          `description: ${JSON.stringify(fm.description || "")}`,
          ...(tools.length ? ["tools:", ...tools.map((t) => `  - ${t}`)] : []),
          "---",
          "",
          `<!-- ${BANNER} -->`,
          "",
        ].join("\n");
        put(`.gemini/agents/${fm.name}.md`, head + translateBody(body, "gemini").trim() + "\n");
      }
    }
  };
  walk(dir);
}

// ── 7. bin/astro — Codex command dispatcher ──────────────────────────────────
// Codex CLI 0.128+ stopped discovering repo-local `.codex/prompts/`, so the
// emitted prompts are documentation there. This dispatcher restores an
// invocation surface: `bin/astro chart` feeds the prompt to `codex exec`.
function emitDispatcher() {
  put(
    "bin/astro",
    `#!/usr/bin/env bash
# ${BANNER}
#
# Astrolabe command dispatcher for CLIs without repo-local slash commands
# (Codex 0.128+ no longer discovers .codex/prompts/). Feeds the emitted prompt
# body to the CLI as a one-shot exec.
#
#   bin/astro <command> [extra args...]     e.g.  bin/astro chart
#   ASTRO_CLI=gemini bin/astro cast 1979-12-31
set -euo pipefail
ROOT="$(cd "$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"
CMD="\${1:-}"; shift || true
CLI="\${ASTRO_CLI:-codex}"
if [ -z "$CMD" ]; then
  echo "usage: bin/astro <command> [args]" >&2
  echo "commands:" >&2
  ls "$ROOT/.codex/prompts" 2>/dev/null | sed 's/\\.md$//' | sed 's/^/  /' >&2
  exit 2
fi
P="$ROOT/.codex/prompts/$CMD.md"
[ -f "$P" ] || { echo "unknown command: $CMD" >&2; exit 2; }
BODY="$(sed '1{/^---$/!q;};1,/^---$/d' "$P")"
ARGS="$*"
PROMPT="\${BODY//\\$ARGUMENTS/$ARGS}"
case "$CLI" in
  codex)  exec codex exec "$PROMPT" ;;
  gemini) exec gemini -p "$PROMPT" ;;
  *)      echo "unsupported ASTRO_CLI: $CLI" >&2; exit 2 ;;
esac
`,
  );
  if (!CHECK) {
    try {
      fs.chmodSync(path.join(ROOT, "bin/astro"), 0o755);
    } catch {
      /* best effort */
    }
  }
}

// ── run ──────────────────────────────────────────────────────────────────────
emitRootDocs();
emitHooks();
emitCodexConfig();
emitCommands();
emitSkills();
emitAgents();
emitDispatcher();

if (CHECK) {
  if (stale.length) {
    console.error(`✗ CLI lanes STALE — ${stale.length} file(s) differ from .claude/ source:`);
    for (const s of stale.slice(0, 20)) console.error(`    ${s}`);
    if (stale.length > 20) console.error(`    … +${stale.length - 20} more`);
    console.error("  fix: node .claude/bin/emit-cli-artifacts.mjs");
    process.exit(1);
  }
  console.log("✓ CLI lanes in sync with .claude/ source (codex + gemini)");
} else {
  console.log(`✓ emitted CLI lanes — ${written} file(s) written (codex + gemini)`);
}
